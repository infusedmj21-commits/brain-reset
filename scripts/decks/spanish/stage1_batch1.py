# --- Numbers ---
for es, en in [('uno', 'one'), ('dos', 'two'), ('tres', 'three'), ('cuatro', 'four'), ('cinco', 'five'), ('seis', 'six'),
               ('siete', 'seven'), ('ocho', 'eight'), ('nueve', 'nine'), ('diez', 'ten'), ('once', 'eleven'), ('doce', 'twelve'),
               ('quince', 'fifteen'), ('veinte', 'twenty'), ('treinta', 'thirty'), ('cincuenta', 'fifty'), ('cien', 'a hundred'), ('mil', 'a thousand')]:
    tips = {'cinco': 'Spain: “thinco”.', 'doce': 'Spain: “dothe”.', 'once': 'Spain: “onthe”.', 'quince': 'Spain: “kinthe”.', 'diez': 'Spain: “dieth”.'}
    n(es, en, ('recog', 'audio') if es in ('cinco', 'doce') else ('recog',), **({'note': tips[es]} if es in tips else {}))

