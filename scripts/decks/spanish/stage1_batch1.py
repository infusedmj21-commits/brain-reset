# Spanish (Spain) stage 1, batch 1: survival chunks, question words, small words, numbers, time.
# Fields: es, en, cards, optional: hint (for English->Spanish prompts), example (es, en), note, say, image
N = []
def n(es, en, cards=('recog',), **kw):
    N.append(dict(es=es, en=en, cards=list(cards), **kw))

# --- Greetings and survival chunks ---
n('hola', 'hello', ('recog', 'prod', 'audio'), note='The h is always silent: “ola”.')
n('buenos días', 'good morning', ('recog', 'prod'))
n('buenas tardes', 'good afternoon / good evening', ('recog', 'prod'), note='Used from about 2pm until it gets dark.')
n('buenas noches', 'good evening / good night', ('recog', 'prod'))
n('adiós', 'goodbye', ('recog', 'prod'))
n('hasta luego', 'see you later / bye', ('recog', 'prod'), note='In Spain this is the everyday “bye”, even if you won’t see them later.')
n('por favor', 'please', ('recog', 'prod'))
n('gracias', 'thank you', ('recog', 'prod', 'audio'), note='Spain: the c sounds like English “th”: “grathias”.')
n('de nada', 'you’re welcome', ('recog', 'prod'))
n('perdón', 'sorry / excuse me', ('recog', 'prod'), example=('Perdón, ¿dónde está el baño?', 'Excuse me, where’s the toilet?'))
n('lo siento', 'I’m sorry', ('recog', 'prod'))
n('vale', 'OK', ('recog', 'prod'), note='Spain’s everyday “OK”. You’ll hear it constantly.')
n('sí', 'yes', ('recog',))
